// Function to check if an IP is blocked
export const isIPBlocked = (ip) => {
  if (!ip) return false;
  
  // Check exact matches
  if (exactBlockedIPs.includes(ip)) {
    return true;
  }
  
  // Check patterns
  for (const pattern of blockedIPPatterns) {
    try {
      const regex = new RegExp(pattern);
      if (regex.test(ip)) {
        return true;
      }
    } catch (e) {
      console.error('Invalid regex pattern:', pattern);
    }
  }
  
  return false;
};

// Function to add IP to blocked list
export const addBlockedIP = (ip) => {
  if (!exactBlockedIPs.includes(ip)) {
    exactBlockedIPs.push(ip);
    return true;
  }
  return false;
};

